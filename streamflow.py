# Helper to find index of a specific date
'''This was written by AI'''
def get_births_for_date(date_str):
    idx = np.where(x == np.datetime64(date_str))[0][0]
    return x[idx], y_1[idx]

#These are the dates of the holiday as the values in a dictionary
holidays = {
    "New Year's Day": '2012-01-01',
    "4th of July": '2012-07-04',
    "Halloween": '2012-10-31',
    "Thanksgiving": '2012-11-27',
    "Christmas": '2012-12-25'
}

#Annotating each holiday with a curved arrow
for label, date_str in holidays.items():
    date_val, birth_val = get_births_for_date(date_str)

    # Place labels below the points and use curved connection styles
    y_text_offset = 250 if label in [ "Christmas"] else -200
    rad_val = 0.6 if label in [ "New Year's Day","Christmas"] else -0.6

    plt.annotate(label,
                 xy=(date_val, birth_val),
                 xytext=(date_val, birth_val + y_text_offset),
                 arrowprops=dict(
                     arrowstyle="->",
                     connectionstyle=f"arc3,rad={rad_val}",
                     color='black',
                     lw=1.5
                 ),
                 horizontalalignment='left' if label in ["New Year's Day"] else 'right' )

'''End AI written code'''

